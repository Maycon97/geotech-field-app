window.getGeotechMemberById = function(id) {
    const data = window.GEOTECH_TEAM_DATA.niveis;
    for (const cat of Object.keys(data)) {
        const found = data[cat].find(m => m.id === id);
        if (found) return found;
    }
    return null;
};

